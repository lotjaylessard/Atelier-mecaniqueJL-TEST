#!/usr/bin/env node
"use strict";
const assert=require("node:assert/strict");
const {plan}=require("./s10-plan-friend-storage-remap.cjs");
const {makeSql}=require("./s10-build-garage-b-import-SQL.cjs");
const uidA="00000000-0000-4000-8000-000000000001",uidB="00000000-0000-4000-8000-000000000002";
const gA="10000000-0000-4000-8000-000000000001",gB="10000000-0000-4000-8000-000000000002";
const base=()=>({clients:[],workorders:[],invoices:[],notes:[],parts:[],services:[],settings:{}});
const a=base();a.clients=[{id:"C1",name:"Fixture A"}];a.invoices=[{id:"FA1",number:"0001",total:101}];
const b=base();b.clients=[{id:"C1",name:"Fixture B"}];b.invoices=[{id:"FA1",number:"0001",total:0,paid:true}];
b.workorders=[{id:"BT1",attachments:[{path:"clients/fixture/receipt.pdf"}]}];
const friendStoragePlan=plan({data:b,objects:[{name:"clients/fixture/receipt.pdf",size:123}]},uidB);
const input={garageA:{garage_id:gA,owner_uid:uidA,data:a},garageB:{garage_id:gB,owner_uid:uidB,data:friendStoragePlan.data},friendStoragePlan};
const original=structuredClone(input);
const result=makeSql(input);
assert.deepEqual(input,original,"must not mutate data");
assert.match(result.sql,/BEGIN;[\s\S]*COMMIT;/);
assert.match(result.sql,/STOP: Garage B already contains data/);
assert.match(result.sql,/STOP: original garage A data mismatch/);
assert.match(result.sql,/STOP: owner\/membership isolation invalid/);
assert.match(result.sql,/STOP: post-import isolation\/data invariant/);
assert.match(result.sql,/two garages, two owners, only A data pre-import/);
assert.match(result.sql,/INSERT INTO public\.garage_data\(user_id,garage_id,data\)/);
assert.ok(!result.sql.includes("Fixture A"),"A business data must not be emitted into B payload");
assert.ok(!result.sql.includes("Fixture B"),"friend business data is encoded in SQL and private");
const encoded=result.sql.match(/decode\('([0-9a-f]+)','hex'\)/)?.[1];
assert.ok(encoded,"hex-encoded friend JSON required");
const actual=JSON.parse(Buffer.from(encoded,"hex").toString("utf8"));
assert.deepEqual(actual,friendStoragePlan.data);
assert.equal(actual.invoices[0].total,0);
assert.equal(actual.invoices[0].paid,true);
assert.equal(actual.workorders[0].attachments[0].path,friendStoragePlan.files[0].target);
assert.equal(result.counts.clients,1);
assert.throws(()=>makeSql({...input,garageB:{...input.garageB,owner_uid:uidA}}),/S10_TWO_GARAGE_MERGE_REFUSED/);
assert.throws(()=>makeSql({...input,garageB:{...input.garageB,data:b}}),/S10_TWO_GARAGE_MERGE_REFUSED/);
console.log("S10_PRIVATE_GARAGE_B_SQL_IMPORT_GUARDS_PASS");
