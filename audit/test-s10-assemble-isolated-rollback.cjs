"use strict";
const assert=require("node:assert/strict"),cp=require("node:child_process"),path=require("node:path");
const r=cp.spawnSync(process.execPath,[path.join(__dirname,"s10-assemble-isolated-rollback.cjs")],{encoding:"utf8",maxBuffer:3e6});
assert.equal(r.status,0,r.stderr);
const s=r.stdout;
assert.ok(s.startsWith("BEGIN;"));
assert.ok(s.trimEnd().endsWith("ROLLBACK;"));
assert.doesNotMatch(s,/\bCOMMIT\s*;/i);
assert.match(s,/CREATE POLICY/);
assert.match(s,/CREATE OR REPLACE FUNCTION public.s08_convert_quote_to_workorder/);
assert.match(s,/CREATE TRIGGER protect_garage_data_ids_trigger/);
assert.ok(s.indexOf("CREATE OR REPLACE FUNCTION public.protect_garage_data_ids")<s.indexOf("CREATE TRIGGER protect_garage_data_ids_trigger"));
assert.ok(s.indexOf("CREATE OR REPLACE FUNCTION public.is_garage_member")<s.indexOf("CREATE POLICY"));
assert.match(s,/CREATE INDEX/);
assert.match(s,/ADD CONSTRAINT/);
assert.match(s,/ADD COLUMN IF NOT EXISTS garage_id/);
assert.doesNotMatch(s,/ADD CONSTRAINT "garage_data_pkey"/);
assert.doesNotMatch(s,/ADD CONSTRAINT "garage_data_user_id_fkey"/);
assert.match(s,/CASCADE.*RESTRICT/);
const ddl=s.slice(0,s.indexOf("-- Fonctions SQL réellement présentes"));
assert.doesNotMatch(ddl,/DROP TABLE|TRUNCATE|DELETE FROM garage_data|UPDATE garage_data/i);
// Les RPC existantes peuvent contenir des UPDATE légitimes; vérifier seulement le DDL externe.
console.log("S10_SQL_ASSEMBLY_TESTS_OK: SQL transactionnel, rollback, contraintes, index, RLS, aucune suppression de données.");
