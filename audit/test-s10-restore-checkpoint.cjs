"use strict";
const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict");
const root=__dirname;
const sql=fs.readFileSync(path.join(root,"s10-local-restore-business-integrity-READ-ONLY.psql"),"utf8");
const ps=fs.readFileSync(path.join(root,"s10-verify-local-restore-vs-checkpoint.ps1"),"utf8");
assert.match(sql,/BEGIN READ ONLY;/);
assert.match(sql,/ROLLBACK;/);
assert.match(sql,/current_database\(\) <> 'atelier_jl_restore_test'/);
assert.match(sql,/inet_server_addr\(\)/);
assert.match(sql,/md5\(data::text\)/);
assert.match(sql,/missing_attached_objects/);
assert.doesNotMatch(sql,/\b(?:INSERT INTO|DELETE FROM|TRUNCATE|DROP TABLE|CREATE TABLE|ALTER TABLE|COMMIT;)\b/i);
assert.match(ps,/-h 127\.0\.0\.1/);
assert.match(ps,/-d \$Database/);
assert.match(ps,/if \(\$Database -ne 'atelier_jl_restore_test'\)/);
assert.match(ps,/json_snapshot_match/);
assert.match(ps,/DIFFERENT_OR_INCOMPLETE_RESTORE/);
assert.match(ps,/exit 2/);
console.log("S10_RESTORE_CHECKPOINT_STATIC_OK: SQL is read-only and PowerShell targets the local restore.");
