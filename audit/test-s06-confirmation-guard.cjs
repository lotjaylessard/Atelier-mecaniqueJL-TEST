"use strict";
const assert=require("node:assert/strict");
const {verifiedPostingReceipt,confirmationMessage}=require("./s06-timer-confirmation-guard.cjs");
const sid="session-1", id="bt-1";
const request={sessionId:sid,workOrderId:id,expectedSessionRevision:5,expectedGarageVersion:12,expectedConfirmedMs:5400000};
const ack={session_id:sid,work_order_id:id,work_order_number:"BT-001",posted_labor_id:sid,session_revision:6,garage_version:13,confirmed_ms:5400000,hours:1.5,hourly_rate:90,total:135};
const remoteSession={id:sid,status:"posted",posted_labor_id:sid,revision:6,confirmed_ms:5400000};
const line={timerSessionId:sid,hours:1.5,rate:90,total:135};
const remoteGarage={version:13,data:{workorders:[{id,number:"BT-001",labor:[line],notes:"Inspection\n\n[S06 minuterie : session-1]\nTravail effectué"}]}};
const input={request,ack,remoteSession,remoteGarage};
assert.throws(()=>confirmationMessage({}),e=>e.code==="not_confirmed");
const copy=JSON.stringify(input);
const receipt=verifiedPostingReceipt(input);
assert.equal(receipt.kind,"verified-post");
assert.equal(receipt.total,135);
assert.ok(Object.isFrozen(receipt));
const message=confirmationMessage(receipt);
assert.match(message.title,/Intervention enregistrée/);
assert.match(message.note,/BT-001/);
assert.match(message.status,/vérifiée/);
assert.equal(JSON.stringify(input),copy,"Aucune mutation des donnees");
const invalid=(changes,code)=>{
 const caseData={...input,...changes};
 assert.throws(()=>verifiedPostingReceipt(caseData),e=>!code||e.code===code);
};
invalid({localChangesPending:true},"pending");
invalid({ack:{...ack,session_id:"autre"}},"ack");
invalid({ack:{...ack,garage_version:12}},"ack");
invalid({ack:{...ack,session_revision:5}},"ack");
invalid({ack:{...ack,confirmed_ms:100}},"ack");
invalid({remoteSession:{...remoteSession,status:"paused"}},"session");
invalid({remoteSession:{...remoteSession,revision:5}},"session");
invalid({remoteSession:{...remoteSession,confirmed_ms:100}},"session");
invalid({remoteGarage:{...remoteGarage,version:12}},"garage");
invalid({remoteGarage:{version:13,data:{workorders:[]}}},"workorder");
invalid({remoteGarage:{version:13,data:{workorders:[{...remoteGarage.data.workorders[0],labor:[]}]}}},"duplicate");
invalid({remoteGarage:{version:13,data:{workorders:[{...remoteGarage.data.workorders[0],notes:"Aucune note"}]}}},"duplicate");
invalid({remoteGarage:{version:13,data:{workorders:[{...remoteGarage.data.workorders[0],labor:[line,line]}]}}},"duplicate");
invalid({remoteGarage:{version:13,data:{workorders:[{...remoteGarage.data.workorders[0],notes:"[S06 minuterie : session-1] [S06 minuterie : session-1]"}]}}},"duplicate");
invalid({remoteGarage:{version:13,data:{workorders:[{...remoteGarage.data.workorders[0],labor:[{...line,total:140}]}]}}},"amount");
invalid({ack:{...ack,work_order_number:"AUTRE"}},"workorder");
assert.equal(JSON.stringify(input),copy);
console.log("S06 : confirmation de succes bloquee jusqu'aux lectures serveur coherentes, duplications et conflits refuses.");
