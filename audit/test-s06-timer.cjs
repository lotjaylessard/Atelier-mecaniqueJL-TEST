"use strict";
const assert=require("node:assert/strict");
const timer=require("./s06-timer-core.cjs");
const T=100000000;
const eq=(s,ms,status)=>{assert.equal(s.confirmedMs,ms);assert.equal(s.status,status);};
let s=timer.makeSession({id:"ses-1",workOrderId:"BT-1",now:T});
eq(s,0,"paused");
s=timer.start(s,T);eq(s,0,"running");
assert.equal(timer.liveMs(s,T+15000),15000);
s=timer.heartbeat(s,T+10000);eq(s,10000,"running");
s=timer.pause(s,T+15000);eq(s,15000,"paused");
assert.equal(timer.liveMs(s,T+100000),15000,"Pause n'accumule pas du temps");
s=timer.start(s,T+60000);
s=timer.heartbeat(s,T+70000);eq(s,25000,"running");
const recovered=timer.recoverAfterClose(s);
eq(recovered,25000,"paused");
assert.equal(timer.liveMs(recovered,T+86400000),25000,"Une nuit ne compte pas");
assert.equal(timer.recoverAfterClose(recovered).confirmedMs,25000,"Recuperation idempotente");
assert.equal(timer.start(recovered,T+86400000).status,"running","Reprise le lendemain");
assert.equal(timer.decimalHours(3600000),1);
assert.equal(timer.decimalHours(2700000),0.75);
assert.equal(timer.decimalHours(15000),0);
assert.throws(()=>timer.start(s,T+60000),/deja en cours/);
assert.throws(()=>timer.heartbeat(recovered,T+90000),/non active/);
assert.throws(()=>timer.heartbeat(s,T-1),/invalide/);
assert.throws(()=>timer.heartbeat(s,T+2*24*60*60*1000),/invalide/);
let finished=timer.finalize(recovered,"labor-unique-1",T+80000);
eq(finished,25000,"posted");
assert.equal(finished.postedLaborId,"labor-unique-1");
assert.throws(()=>timer.finalize(finished,"labor-unique-2",T+80001),/Mettre en pause/);
assert.throws(()=>timer.start(finished,T+100000),/deja facture/);
assert.throws(()=>timer.finalize(s,"labor-2",T+80001),/Mettre en pause/);
const untouched=timer.makeSession({id:"s2",workOrderId:"BT-2",now:T});
timer.start(untouched,T+1);
eq(untouched,0,"paused");
console.log("S06-F01 : pause, reprise, fermeture, recuperation, absence de double facturation : OK.");
