"use strict";
// S06-F04c : panneau toujours visible sous Menu, aucune minuterie reelle.
const fs=require("node:fs");
const assert=require("node:assert/strict");
const html=fs.readFileSync("index.html","utf8");
const once=(regex,msg)=>assert.equal((html.match(regex)||[]).length,1,msg);
once(/id="s06SidebarTimer"/g,"un seul panneau permanent");
assert.doesNotMatch(html,/id="s06PreviewToggle"/,"pas de bouton apercu");
assert.doesNotMatch(html,/id="s06PreviewPanel"/,"pas de popup");
const posMenu=html.indexOf('<h2>Menu</h2>');
const posTimer=html.indexOf('<section id="s06SidebarTimer"');
const posDashboard=html.indexOf('<button class="navBtn" data-page="page-dashboard"');
assert.ok(posMenu>=0&&posTimer>posMenu&&posDashboard>posTimer,"entre Menu et Dashboard");
const widget=html.slice(posTimer,html.indexOf("</section>",posTimer));
assert.match(widget,/Minuterie/);
assert.match(widget,/● Inactive/);
assert.match(widget,/# BT :/);
assert.match(widget,/Véhicule :/);
assert.match(widget,/Description :/);
assert.doesNotMatch(widget,/Client :/,"client cache volontairement");
assert.match(widget,/00:00:00/);
assert.match(widget,/Aperçu seulement/);
once(/<button type="button" disabled>▶ Démarrer<\/button>/g,"start interdit");
once(/<button type="button" disabled>⏸ Pause<\/button>/g,"pause interdite");
for(const forbidden of [/localStorage/i,/sessionStorage/i,/\.rpc\(/,/\.from\(/,/setInterval\(/,/fetch\(/,/WO_TIMER_/])assert.doesNotMatch(widget,forbidden,"aucun effet en panneau");
assert.match(html,/id="cloudSyncIndicator"/,"indicateur de sync preserve");
assert.match(html,/id="woTimerBtn"/,"minuterie historique preservee");
assert.match(html,/#sidebar > \.navBtn\{[^}]*min-height:30px/,"boutons conserves et compacts");
assert.match(html,/#s06SidebarTimer \.s06-timer-description\{[^}]*-webkit-line-clamp:2/,"description limitee");
assert.match(html,/#sidebar\{[^}]*scrollbar-width:none/,"barre de defilement visuelle masquee");
console.log("S06-F04d : panneau compact BT/vehicule/description, menu preserve, aucune action active.");
